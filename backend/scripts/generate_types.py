#!/usr/bin/env python3
"""OpenAPI schema and TypeScript type definitions generator.

Extracts OpenAPI 3.1 schema from FastAPI and compiles exact, fully-typed
TypeScript interfaces for frontend consumption.
"""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import sys
from typing import Any

# Ensure project roots are on path and host-compatible env vars are set
ROOT_DIR = Path(__file__).resolve().parent.parent.parent
BACKEND_DIR = ROOT_DIR / "backend"
FRONTEND_DIR = ROOT_DIR / "frontend"

sys.path.insert(0, str(BACKEND_DIR))
os.environ.setdefault("STATIC_DIR", str(BACKEND_DIR / "static"))
os.environ.setdefault("TEMP_DIR", "/tmp/clipper")


def get_openapi_spec() -> dict[str, Any]:
    """Import FastAPI application and retrieve OpenAPI specification."""
    from app.main import app

    return app.openapi()


def resolve_type_ref(ref_str: str) -> str:
    """Extract schema name from #/components/schemas/Name."""
    if ref_str.startswith("#/components/schemas/"):
        return ref_str.split("/")[-1]
    return "unknown"


def schema_to_ts_type(prop_schema: dict[str, Any], parent_prop_name: str = "") -> str:
    """Convert an OpenAPI property schema into a TypeScript type expression."""
    if "$ref" in prop_schema:
        return resolve_type_ref(prop_schema["$ref"])

    if "anyOf" in prop_schema:
        sub_types = []
        for item in prop_schema["anyOf"]:
            sub_types.append(schema_to_ts_type(item, parent_prop_name))
        # Deduplicate while preserving order
        unique_types = []
        for t in sub_types:
            if t not in unique_types:
                unique_types.append(t)
        return " | ".join(unique_types)

    if "allOf" in prop_schema:
        sub_types = [schema_to_ts_type(item, parent_prop_name) for item in prop_schema["allOf"]]
        return " & ".join(sub_types)

    if "oneOf" in prop_schema:
        sub_types = [schema_to_ts_type(item, parent_prop_name) for item in prop_schema["oneOf"]]
        return " | ".join(sub_types)

    if "enum" in prop_schema:
        return " | ".join(json.dumps(val) for val in prop_schema["enum"])

    prop_type = prop_schema.get("type")

    if prop_type == "string":
        return "string"
    if prop_type in ("integer", "number"):
        return "number"
    if prop_type == "boolean":
        return "boolean"
    if prop_type == "null":
        return "null"
    if prop_type == "array":
        items_schema = prop_schema.get("items")
        if not items_schema:
            return "unknown[]"
        item_type = schema_to_ts_type(items_schema, parent_prop_name)
        if " | " in item_type or " & " in item_type:
            return f"({item_type})[]"
        return f"{item_type}[]"
    if prop_type == "object":
        if "additionalProperties" in prop_schema and isinstance(prop_schema["additionalProperties"], dict):
            val_type = schema_to_ts_type(prop_schema["additionalProperties"], parent_prop_name)
            return f"Record<string, {val_type}>"
        return "Record<string, unknown>"

    return "unknown"


def format_jsdoc(description: str | None, indent: str = "") -> list[str]:
    """Format description text into JSDoc comments."""
    if not description:
        return []
    lines = description.strip().split("\n")
    if len(lines) == 1:
        return [f"{indent}/** {lines[0]} */"]
    jsdoc = [f"{indent}/**"]
    for line in lines:
        jsdoc.append(f"{indent} * {line}" if line else f"{indent} *")
    jsdoc.append(f"{indent} */")
    return jsdoc


def generate_typescript(spec: dict[str, Any]) -> str:
    """Generate complete TypeScript definition file from OpenAPI schema dictionary."""
    schemas: dict[str, Any] = spec.get("components", {}).get("schemas", {})
    output_lines: list[str] = [
        "/**",
        " * Auto-generated TypeScript definitions from FastAPI OpenAPI schema.",
        " * Generated by backend/scripts/generate_types.py. Do not edit directly.",
        " */",
        "",
    ]

    # Explicitly define PipelineStage union for convenience and strong typing
    output_lines.extend([
        "export type PipelineStage =",
        '  | "queued"',
        '  | "downloading"',
        '  | "transcribing"',
        '  | "analyzing"',
        '  | "rendering"',
        '  | "completed"',
        '  | "completed_with_warnings"',
        '  | "partial"',
        '  | "failed"',
        '  | "expired";',
        "",
    ])

    # Desired declaration order for readability
    priority_order = [
        "PipelineErrorCode",
        "WebcamRegion",
        "JobErrorDetail",
        "JobWarning",
        "JobCreateRequest",
        "ClipResult",
        "JobStatusResponse",
        "ValidationError",
        "HTTPValidationError",
    ]

    sorted_names = [name for name in priority_order if name in schemas]
    for name in sorted(schemas.keys()):
        if name not in sorted_names:
            sorted_names.append(name)

    for name in sorted_names:
        schema = schemas[name]
        description = schema.get("description")
        jsdoc = format_jsdoc(description)
        if jsdoc:
            output_lines.extend(jsdoc)

        # Enums
        if "enum" in schema and schema.get("type") == "string":
            enum_vals = schema["enum"]
            output_lines.append(f"export type {name} =")
            for i, val in enumerate(enum_vals):
                sep = ";" if i == len(enum_vals) - 1 else ""
                output_lines.append(f"  | {json.dumps(val)}{sep}")
            output_lines.append("")
            continue

        # Object / Interface
        properties = schema.get("properties", {})
        required_props = set(schema.get("required", []))

        output_lines.append(f"export interface {name} {{")
        for prop_name, prop_schema in properties.items():
            prop_doc = format_jsdoc(prop_schema.get("description"), indent="  ")
            if prop_doc:
                output_lines.extend(prop_doc)

            is_required = prop_name in required_props
            opt_mark = "" if is_required else "?"

            # Use PipelineStage alias for status & stage on JobStatusResponse
            if name == "JobStatusResponse" and prop_name in ("status", "stage"):
                ts_type = "PipelineStage"
            else:
                ts_type = schema_to_ts_type(prop_schema, prop_name)

            output_lines.append(f"  {prop_name}{opt_mark}: {ts_type};")

        output_lines.append("}")
        output_lines.append("")

    # Add backwards-compatibility aliases
    output_lines.extend([
        "/** Backwards-compatible alias for JobStatusResponse. */",
        "export type JobStatus = JobStatusResponse;",
        "",
    ])

    return "\n".join(output_lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate TypeScript types from FastAPI OpenAPI.")
    parser.add_argument(
        "--check",
        action="store_true",
        help="Check whether generated files are in sync without writing changes.",
    )
    args = parser.parse_args()

    spec = get_openapi_spec()
    spec_json = json.dumps(spec, indent=2, sort_keys=True) + "\n"
    ts_code = generate_typescript(spec)

    openapi_path = BACKEND_DIR / "openapi.json"
    ts_path = FRONTEND_DIR / "src" / "types" / "api.ts"

    if args.check:
        in_sync = True
        if not openapi_path.exists() or openapi_path.read_text(encoding="utf-8") != spec_json:
            print(f"[ERROR] {openapi_path} is out of sync with FastAPI schema.")
            in_sync = False

        if not ts_path.exists() or ts_path.read_text(encoding="utf-8") != ts_code:
            print(f"[ERROR] {ts_path} is out of sync with FastAPI schema.")
            in_sync = False

        if not in_sync:
            print("Run 'npm run generate-types' or 'backend/.venv/bin/python backend/scripts/generate_types.py' to update.")
            return 1

        print("API contract verification passed: OpenAPI and TypeScript types are in sync.")
        return 0

    # Ensure target directory exists
    ts_path.parent.mkdir(parents=True, exist_ok=True)

    openapi_path.write_text(spec_json, encoding="utf-8")
    ts_path.write_text(ts_code, encoding="utf-8")

    print(f"Successfully generated OpenAPI specification: {openapi_path}")
    print(f"Successfully generated TypeScript types: {ts_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
